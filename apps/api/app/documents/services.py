"""Document upload validation and orchestration.

The server never trusts the client for size, MIME type or storage key: the body
is read in bounded chunks, the SHA-256 and the size are computed locally, the
format comes from magic bytes and the key is generated by the API. The object
is written to private storage before the active metadata row exists, and a
failed metadata write compensates the object.
"""

